"""Explicit migration runner; application startup never creates tables."""

import asyncio

from alembic import context
from sqlalchemy import Connection, pool
from sqlalchemy.engine import URL
from sqlalchemy.ext.asyncio import create_async_engine

from app.core.config import get_settings
from app.db.models import Base

config = context.config
target_metadata = Base.metadata


def database_url() -> str | URL:
    override = config.attributes.get("database_url")
    if isinstance(override, (str, URL)):
        return override
    value = get_settings().database_url
    if value is None:
        raise RuntimeError("Configure RF_DATABASE_URL before running migrations")
    return value.get_secret_value()


def run_sync_migrations(connection: Connection) -> None:
    def include_name(name: str | None, type_: str, parent_names: dict[str, str | None]) -> bool:
        # An unrelated table must never become an autogenerated DROP TABLE proposal.
        return type_ != "table" or name in target_metadata.tables

    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
        include_name=include_name,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_online() -> None:
    engine = create_async_engine(database_url(), poolclass=pool.NullPool, hide_parameters=True)
    try:
        async with engine.connect() as connection:
            await connection.run_sync(run_sync_migrations)
    finally:
        await engine.dispose()


if context.is_offline_mode():
    context.configure(
        url=database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()
else:
    asyncio.run(run_online())
